#!/usr/bin/env python3
"""Rebuild the public non-personal T-route research CSVs and SVG figures from
committed model/source files, not from temporary ChatGPT attachments.
Standard library only. Outputs are illustrative, never clinical predictions.
"""
import csv
import json
import math
import sys
from collections import defaultdict
from pathlib import Path
from xml.sax.saxutils import escape

import t_route_calibration_01 as routes
import t_ichihara_2020_fit as study

COLORS=("#2563eb","#d97706","#16a34a","#a855f7","#be123c","#0891b2")

def make_svg(title, xlabel, ylabel, groups, target, points=None):
    width,height=980,540
    x0,y0,x1,y1=85,65,920,440
    allrows=[point for _,arr in groups for point in arr]
    if points:
        allrows += [(x,y) for x,y,*_ in points]
    xmin=min(x for x,_ in allrows);xmax=max(x for x,_ in allrows)
    ymin=min(0.,min(y for _,y in allrows))
    ymax=max(y for _,y in allrows)*1.1+1e-10
    def x(v): return x0+(v-xmin)/(xmax-xmin or 1.)*(x1-x0)
    def y(v): return y1-(v-ymin)/(ymax-ymin or 1.)*(y1-y0)
    out=[f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" role="img" aria-label="{escape(title)}">',
         '<rect width="980" height="540" fill="#ffffff"/>',
         f'<text x="{width/2}" y="33" text-anchor="middle" font-size="19" font-family="sans-serif" fill="#111827">{escape(title)}</text>']
    for i in range(6):
        v=ymin+(ymax-ymin)*i/5
        yy=y(v)
        out.append(f'<line x1="{x0}" y1="{yy:.2f}" x2="{x1}" y2="{yy:.2f}" stroke="#e5e7eb"/>')
        out.append(f'<text x="{x0-9}" y="{yy+4:.2f}" text-anchor="end" font-size="12" font-family="sans-serif" fill="#374151">{v:.1f}</text>')
    for i in range(6):
        v=xmin+(xmax-xmin)*i/5
        xx=x(v)
        out.append(f'<text x="{xx:.2f}" y="{y1+20}" text-anchor="middle" font-size="12" font-family="sans-serif" fill="#374151">{v:.0f}</text>')
    out.append(f'<path d="M{x0},{y0}V{y1}H{x1}" stroke="#334155" fill="none"/>')
    out.append(f'<text x="{(x0+x1)/2}" y="485" text-anchor="middle" font-size="15" fill="#111827" font-family="sans-serif">{escape(xlabel)}</text>')
    out.append(f'<text x="20" y="260" text-anchor="middle" transform="rotate(-90 20 260)" font-size="15" fill="#111827" font-family="sans-serif">{escape(ylabel)}</text>')
    for i,(label,data) in enumerate(groups):
        if not data: continue
        poly=" ".join(f'{x(xx):.2f},{y(yy):.2f}' for xx,yy in data)
        color=COLORS[i%len(COLORS)]
        out.append(f'<polyline points="{poly}" stroke="{color}" stroke-width="2.1" fill="none"/>')
    if points:
        for xx,yy,is_hold in points:
            color="#b91c1c" if is_hold else "#111827"
            out.append(f'<circle cx="{x(xx):.2f}" cy="{y(yy):.2f}" r="5" fill="#fff" stroke="{color}" stroke-width="2.6"/>')
    legend=[label for label,_ in groups]+(["Human group mean (red=held out)" if points else ""] if points else [])
    for i,label in enumerate(legend):
        xx=95+(i%3)*280; yy=500+(i//3)*20
        color=COLORS[i] if i<len(groups) else "#111827"
        out.append(f'<line x1="{xx}" y1="{yy}" x2="{xx+20}" y2="{yy}" stroke="{color}" stroke-width="3"/>')
        out.append(f'<text x="{xx+25}" y="{yy+4}" font-size="12" fill="#1f2937" font-family="sans-serif">{escape(label)}</text>')
    out.append('</svg>')
    target.write_text("\n".join(out)+"\n",encoding="utf-8")

def run(target):
    target.mkdir(parents=True,exist_ok=True)
    # Committed route model is the single source for this output, not historic local
    # ad-hoc exploratory files. Regenerated bytes need not match old snapshot hashes.
    routes.export(routes.build(), target)
    human=study.checks()
    (target/"ichihara_2020_fit.json").write_text(
        json.dumps(human,indent=2,ensure_ascii=False)+"\n",encoding="utf-8")
    with (target/"ichihara_2020_points_and_fit.csv").open("w",newline="",encoding="utf-8") as f:
        writer=csv.writer(f)
        writer.writerow(["day","human_mean_ng_ml","human_sd_ng_ml","mixture_research_fit_ng_ml","single_exponential_ng_ml","group"])
        for i,day in enumerate(study.DAYS):
            g="baseline" if i==0 else ("held_out" if i in study.HOLD else "training")
            writer.writerow([day,study.MEAN[i],study.SD[i],
                human["two_input"]["predictions_ng_ml"][i],
                human["simple_single_input"]["predictions_ng_ml"][i],g])
    rows=defaultdict(list)
    with (target/"illustrative_curves.csv").open(newline="",encoding="utf-8") as f:
        for z in csv.DictReader(f):
            rows[(z["product"],z["model_scenario"])].append((float(z["days_since_first_dose"]),float(z["model_value"])))
    for prod,fn,scale,ylab in [
        ("ANDROGEL_50","androgel_50_illustrative.svg",15,"ng/mL above assumed baseline"),
        ("ANDROTARDYL","androtardyl_illustrative.svg",30,"total T, ng/mL"),
        ("NEBIDO","nebido_illustrative.svg",470,"total T, nmol/L")]:
        groups=[(scenario,vals) for (product,scenario),vals in sorted(rows.items()) if product==prod]
        if not groups:raise ValueError(f"missing generated product {prod}")
        make_svg(prod+" — ILLUSTRATIVE, NOT VALIDATED","Days since first dose",ylab,groups,target/fn)
    groups=[
        ("2-input model",[(d,v) for d,v in zip(study.DAYS,human["two_input"]["predictions_ng_ml"])]),
        ("single-input model",[(d,v) for d,v in zip(study.DAYS,human["simple_single_input"]["predictions_ng_ml"])])]
    points=[(d,v,i in study.HOLD) for i,(d,v) in enumerate(zip(study.DAYS,study.MEAN))]
    make_svg("Ichihara 2020 N=10 group means — research fit, NOT validated",
             "Days since 250mg enanthate injection","T, ng/mL",groups,
             target/"ichihara_2020_comparison.svg",points)
    return [x.name for x in sorted(target.iterdir()) if x.is_file()]

if __name__=="__main__":
    out=Path(sys.argv[1] if len(sys.argv)>1 else "t_route_rebuilt")
    files=run(out)
    print("Research-only outputs:",", ".join(files))
